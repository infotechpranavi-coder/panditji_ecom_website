export function lookupPhrase(text: string, locale: Locale): string | null {
  if (!text || locale === 'en') return locale === 'en' ? text : null
  const exact = phraseBook[text.trim()]
  if (exact) return exact[locale]
  // case-insensitive
  const key = Object.keys(phraseBook).find((k) => k.toLowerCase() === text.trim().toLowerCase())
  if (key) return phraseBook[key][locale]
  return null
}

const memoryCache = new Map<string, string>()

function cacheKey(text: string, locale: Locale) {
  return `${locale}::${text}`
}

export function getCachedTranslation(text: string, locale: Locale): string | null {
  if (locale === 'en') return text
  const fromBook = lookupPhrase(text, locale)
  if (fromBook) return fromBook
  return memoryCache.get(cacheKey(text, locale)) || null
}

export function setCachedTranslation(text: string, locale: Locale, translated: string) {
  memoryCache.set(cacheKey(text, locale), translated)
  try {
    const storeKey = `bps_tx_${locale}`
    const raw = localStorage.getItem(storeKey)
    const map = raw ? JSON.parse(raw) : {}
    map[text] = translated
    localStorage.setItem(storeKey, JSON.stringify(map))
  } catch {
    // ignore
  }
}

export function loadLocalCache(locale: Locale) {
  if (typeof window === 'undefined' || locale === 'en') return
  try {
    const raw = localStorage.getItem(`bps_tx_${locale}`)
    if (!raw) return
    const map = JSON.parse(raw) as Record<string, string>
    Object.entries(map).forEach(([k, v]) => memoryCache.set(cacheKey(k, locale), v))
  } catch {
    // ignore
  }
}
